-- Borrado de tablas en orden inverso a sus dependencias
DROP TABLE detalle_pedido CASCADE CONSTRAINTS;
DROP TABLE pedidos CASCADE CONSTRAINTS;
DROP TABLE platos CASCADE CONSTRAINTS;
DROP TABLE categorias_plato CASCADE CONSTRAINTS;
DROP TABLE mesas CASCADE CONSTRAINTS;

-- 1. Tabla: mesas
CREATE TABLE mesas (
    numero NUMBER GENERATED BY DEFAULT AS IDENTITY (NOCACHE),
    capacidad NUMBER NOT NULL,
    activa NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT pk_mesas PRIMARY KEY (numero),
    CONSTRAINT ck_mesas_activa CHECK (activa IN (0, 1))
);

-- 2. Tabla: categorias_plato
CREATE TABLE categorias_plato (
    id_categoria NUMBER GENERATED BY DEFAULT AS IDENTITY (NOCACHE),
    nombre VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_categorias PRIMARY KEY (id_categoria),
    CONSTRAINT uq_categorias_nombre UNIQUE (nombre)
);

-- 3. Tabla: platos
CREATE TABLE platos (
    codigo VARCHAR2(20) NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    id_categoria NUMBER NOT NULL,
    precio NUMBER(10,2) NOT NULL,
    disponible NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT pk_platos PRIMARY KEY (codigo),
    CONSTRAINT fk_platos_categoria FOREIGN KEY (id_categoria) REFERENCES categorias_plato(id_categoria),
    CONSTRAINT ck_platos_precio CHECK (precio >= 0),
    CONSTRAINT ck_platos_disponible CHECK (disponible IN (0, 1))
);
CREATE INDEX idx_fk_platos_categoria ON platos(id_categoria);

-- 4. Tabla: pedidos (Entidad Principal)
CREATE TABLE pedidos (
    id_pedido NUMBER GENERATED BY DEFAULT AS IDENTITY (NOCACHE),
    numero_mesa NUMBER NOT NULL,
    garzon VARCHAR2(100) NOT NULL,
    fecha TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    propina NUMBER(10,2) DEFAULT 0 NOT NULL,
    total NUMBER(10,2) DEFAULT 0 NOT NULL,
    estado VARCHAR2(20) DEFAULT 'abierto' NOT NULL,
    CONSTRAINT pk_pedidos PRIMARY KEY (id_pedido),
    CONSTRAINT fk_pedidos_mesa FOREIGN KEY (numero_mesa) REFERENCES mesas(numero),
    CONSTRAINT ck_pedidos_propina CHECK (propina >= 0),
    CONSTRAINT ck_pedidos_total CHECK (total >= 0),
    CONSTRAINT ck_pedidos_estado CHECK (estado IN ('abierto', 'en_cocina', 'servido', 'pagado', 'anulado'))
);
CREATE INDEX idx_fk_pedidos_mesa ON pedidos(numero_mesa);

-- 5. Tabla: detalle_pedido
CREATE TABLE detalle_pedido (
    id_pedido NUMBER NOT NULL,
    codigo_plato VARCHAR2(20) NOT NULL,
    cantidad NUMBER NOT NULL,
    precio_unitario NUMBER(10,2) NOT NULL,
    observacion VARCHAR2(255),
    CONSTRAINT pk_detalle_pedido PRIMARY KEY (id_pedido, codigo_plato),
    CONSTRAINT fk_detalle_pedido FOREIGN KEY (id_pedido) REFERENCES pedidos(id_pedido),
    CONSTRAINT fk_detalle_plato FOREIGN KEY (codigo_plato) REFERENCES platos(codigo),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_precio CHECK (precio_unitario >= 0)
);
CREATE INDEX idx_fk_detalle_pedido ON detalle_pedido(id_pedido);
CREATE INDEX idx_fk_detalle_plato ON detalle_pedido(codigo_plato);